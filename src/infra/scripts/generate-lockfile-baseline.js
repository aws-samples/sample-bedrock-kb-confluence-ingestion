/**
 * Generate the preservation baseline snapshot for the brace-expansion
 * CVE-2026-45149 bugfix (Property 2: Preservation).
 *
 * This script captures the resolution map (lockfile `packages` key -> resolved
 * version) of the CURRENT (UNFIXED) `src/infra/package-lock.json`, EXCLUDING the
 * single buggy entry (the bundled brace-expansion@5.0.5 under aws-cdk-lib). The
 * resulting `test/fixtures/lockfile-baseline.json` is committed and frozen: it is
 * the "before the fix" snapshot that the preservation property test (task 2)
 * compares the post-fix lockfile against.
 *
 * Observation-first methodology: run this BEFORE applying the fix (task 3.1) so the
 * baseline reflects the genuine pre-fix resolution data.
 *
 * Usage (from src/infra, Node 20 via Docker alias):
 *   node20 scripts/generate-lockfile-baseline.js
 */
const fs = require('fs');
const path = require('path');

const INFRA_ROOT = path.resolve(__dirname, '..');
const LOCKFILE_PATH = path.join(INFRA_ROOT, 'package-lock.json');
const BASELINE_PATH = path.join(INFRA_ROOT, 'test', 'fixtures', 'lockfile-baseline.json');

/** Derive the package name from a lockfile `packages` key (last node_modules segment). */
function nameFromKey(key) {
  if (!key) return '';
  const idx = key.lastIndexOf('node_modules/');
  return idx === -1 ? key : key.slice(idx + 'node_modules/'.length);
}

/**
 * Bug condition (from design):
 *   isBugCondition(entry) = name == "brace-expansion"
 *                           AND version == "5.0.5"
 *                           AND inBundle == true
 */
function isBugCondition(key, entry) {
  return (
    nameFromKey(key) === 'brace-expansion' &&
    entry.version === '5.0.5' &&
    entry.inBundle === true
  );
}

function main() {
  const lock = JSON.parse(fs.readFileSync(LOCKFILE_PATH, 'utf8'));
  const packages = lock.packages || {};

  const resolution = {};
  let excluded = 0;
  for (const [key, entry] of Object.entries(packages)) {
    if (!entry || typeof entry.version !== 'string') continue; // only versioned entries
    if (isBugCondition(key, entry)) {
      excluded += 1;
      continue; // do NOT snapshot the buggy entry
    }
    resolution[key] = entry.version;
  }

  const baseline = {
    _comment:
      'Frozen pre-fix (UNFIXED) resolution snapshot for brace-expansion CVE-2026-45149 ' +
      'preservation tests. Generated by scripts/generate-lockfile-baseline.js. The buggy ' +
      'bundled brace-expansion@5.0.5 under aws-cdk-lib is intentionally excluded.',
    lockfileVersion: lock.lockfileVersion,
    generatedFrom: 'package-lock.json (UNFIXED tree)',
    excludedBuggyEntries: excluded,
    entryCount: Object.keys(resolution).length,
    resolution,
  };

  fs.mkdirSync(path.dirname(BASELINE_PATH), { recursive: true });
  fs.writeFileSync(BASELINE_PATH, JSON.stringify(baseline, null, 2) + '\n', 'utf8');

  // eslint-disable-next-line no-console
  console.log(
    `Wrote baseline: ${BASELINE_PATH}\n  entries: ${baseline.entryCount}, excluded buggy: ${excluded}`,
  );
}

main();
